import 'package:arta/models/ledger.dart';
import 'package:arta/models/money.dart';
import 'package:arta/models/schedule.dart';

ScheduleRule schedule({
  String id = 'rule',
  String start = '2026-01-31',
  String amount = '6000',
  String fee = '0',
  String source = 'bank',
  String category = 'Biaya bank',
  String? destination,
  TransactionKind kind = TransactionKind.expense,
  RepeatFrequency frequency = RepeatFrequency.monthly,
  int interval = 1,
  bool endOfMonth = false,
  int? monthDay,
  int? count,
  String? end,
  bool installments = false,
  ScheduleMode mode = ScheduleMode.confirm,
  String zone = 'Asia/Jakarta',
  ScheduleState state = ScheduleState.active,
}) => ScheduleRule(
  id: id,
  name: 'Biaya bank',
  kind: kind,
  accountId: source,
  destinationId: destination,
  amount: Money.input(amount),
  fee: Money.input(fee),
  category: kind == TransactionKind.transfer ? '' : category,
  note: '',
  startDate: start,
  frequency: frequency,
  interval: interval,
  endOfMonth: endOfMonth,
  monthDay: monthDay,
  count: count,
  endDate: end,
  installments: installments,
  mode: mode,
  zone: zone,
  state: state,
  createdAt: '2026-11-19T00:00:00.000Z',
);

Account account(String id, String opening) => Account(
  id: id,
  name: id,
  kind: AccountKind.bank,
  opening: Money.input(opening),
  createdAt: '2026-11-19T00:00:00.000Z',
);
LedgerTransaction transaction({
  String id = 'tx',
  TransactionKind kind = TransactionKind.expense,
  String source = 'bank',
  String category = 'Biaya bank',
  String? destination,
  String amount = '100',
  String fee = '0',
  String date = '2026-11-19',
}) => LedgerTransaction(
  id: id,
  kind: kind,
  accountId: source,
  destinationId: destination,
  amount: Money.input(amount),
  fee: Money.input(fee),
  date: date,
  category: kind == TransactionKind.transfer ? '' : category,
  note: '',
  createdAt: '2026-11-19T00:00:00.000Z',
);
